#!/usr/bin/env bash
# setup_tool_bridges.sh — wire AGENTS.md into every coding agent's expected config.
#
# AGENTS.md is the single source of truth. This script creates bridge files
# so tools that read CLAUDE.md, .cursorrules, .github/copilot-instructions.md,
# or .aider.conf.yml all find their way back to the same instructions.
#
# Usage:
#   bash scripts/setup_tool_bridges.sh              # create pointer files
#   bash scripts/setup_tool_bridges.sh --dry-run    # show what would happen
#   bash scripts/setup_tool_bridges.sh --force      # overwrite existing bridges
#   bash scripts/setup_tool_bridges.sh --clean      # remove all bridge files
#
# Idempotent. Existing files are left alone unless --force.

set -euo pipefail

DRY=0
FORCE=0
CLEAN=0

for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY=1 ;;
    --force)   FORCE=1 ;;
    --clean)   CLEAN=1 ;;
    -h|--help)
      sed -n '2,/^$/s/^# //p' "$0"
      exit 0
      ;;
    *) echo "unknown flag: $arg (try --help)" >&2; exit 2 ;;
  esac
done

cd "$(git rev-parse --show-toplevel 2>/dev/null || pwd)"

say() { printf '%s\n' "$*"; }

[ -f AGENTS.md ] || {
  echo "ERROR: no AGENTS.md in $(pwd)." >&2
  exit 1
}

# All bridge files this script manages
BRIDGES=(
  "CLAUDE.md"
  ".cursorrules"
  ".cursor/rules/python-source.mdc"
  ".cursor/rules/tests.mdc"
  ".cursor/rules/cdk-typescript.mdc"
  ".cursor/rules/terraform.mdc"
  ".cursor/rules/docs.mdc"
  ".github/copilot-instructions.md"
  ".aider.conf.yml"
  ".gemini/settings.json"
  ".windsurfrules"
  ".kiro/steering/RULES.md"
)

if [ "$CLEAN" = 1 ]; then
  say "Cleaning bridge files..."
  for f in "${BRIDGES[@]}"; do
    if [ -f "$f" ]; then
      if [ "$DRY" = 1 ]; then
        say "  would remove  $f"
      else
        rm "$f"
        say "  removed  $f"
      fi
    fi
  done
  say "Done."
  exit 0
fi

say "AGENTS.md found in $(pwd)"
[ "$DRY" = 1 ] && say "(dry run)"
say ""

write_file() {
  local path="$1" content="$2"
  if [ -e "$path" ] && [ "$FORCE" != 1 ]; then
    say "  skip    $path (exists, use --force to overwrite)"
    return
  fi
  if [ "$DRY" = 1 ]; then
    say "  create  $path"
    return
  fi
  mkdir -p "$(dirname "$path")"
  if [ -e "$path" ]; then
    cp -p "$path" "$path.bak"
    say "  overwrite  $path (backup at $path.bak)"
  else
    say "  create  $path"
  fi
  printf '%s\n' "$content" > "$path"
}

