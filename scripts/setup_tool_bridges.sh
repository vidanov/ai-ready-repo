# Source of truth: AGENTS.md

## How to work with this repo

This is a verification-first repository. Every rule that can be enforced
by a tool is enforced by a tool. AGENTS.md documents only what tools
cannot check.

**Before making changes:**
1. Read \`AGENTS.md\` for the full constraint surface.
2. Run \`make verify\` to see what green looks like before you touch anything.
3. Check \`docs/adr/\` for architecture decisions that explain why things
   are the way they are. Each ADR has a Retirement section — if the
   constraint looks wrong, the ADR tells you when to remove it.

**While making changes:**
- Run \`make verify-fast\` for quick feedback (format + lint + typecheck).
- Import boundaries are enforced by CI. If \`make import-check\` fails,
  the import direction is wrong (domain cannot import infrastructure).
- Do not weaken tests to make them pass. Do not disable linter rules.
  \`make verify-tamperproof\` will catch it.

**Before claiming done:**
- Run \`make verify\` (the full ladder).
- If you added a new rule, add a firing condition (drill) that proves
  the rule can convict. A gate that has never fired is indistinguishable
  from a gate that cannot fire.

## Verification
\`make verify\` runs: format-check → lint → typecheck → import-check →
test-unit → validate-adrs. All must pass.

## Import boundaries (CI-enforced)
Three layers: domain → application → infrastructure. One-way only.
- \`domain/\` must NOT import from \`application/\` or \`infrastructure/\`.
- \`application/\` may import \`domain/\`.
- \`infrastructure/\` may import \`domain/\` and \`application/\`.

## Drills (prove gates work)
- \`make drill-transition-guard\` — domain guard fires on invalid transition
- \`make drill-import-check\` — import boundary rejects forbidden import
- \`make drill-import-permit\` — import boundary permits legal import
- \`make drill-deny-catalog\` — deny rules golden-file locked and firing
- \`make drill-dead-config\` — no dead config keys in pyproject.toml
- \`make drill-ci-coverage\` — every verification target runs in CI

## Non-obvious constraints
- Tests require 80% coverage (\`pyproject.toml\` fail_under).
- \`CODEOWNERS\` routes sensitive paths to named teams.
- The deny catalog (\`scripts/deny_catalog_golden.json\`) is additive-only.
  You can add deny patterns. You cannot remove baseline ones.
- ADRs must have Verification and Retirement sections.

## When you are stuck
- If the task looks impossible, say so and stop. Do not escalate to
  creative workarounds outside the task scope.
- If a test fails and you do not understand why, read the ADR linked
  in the test comment before changing the test.
- If you are unsure whether an import is allowed, run \`make import-check\`
  rather than guessing. The linter is the authority, not the instruction."

