def detect_stack(repo: Path) -> list[str]:
    """Detect which stacks are present in the repo."""
    found = []
    for name, config in STACKS.items():
        detect_files = str(config["detect"]).split(",")
        for pattern in detect_files:
            if pattern.startswith("*"):
                if list(repo.glob(pattern)):
                    found.append(name)
                    break
            elif (repo / pattern).exists():
                found.append(name)
                break
    return found


def generate_makefile(stack_name: str, config: dict) -> str:
    """Generate a Makefile for the detected stack."""
    lines = [WARNING.replace("# ", "## "), ""]
    lines.append(".DEFAULT_GOAL := help\n")

    if config.get("bootstrap"):
        lines.append(f".PHONY: bootstrap")
        lines.append(f"bootstrap: ## Set up development environment")
        lines.append(f"\t{config['bootstrap']}\n")

    if config.get("formatter"):
        lines.append(f".PHONY: format-check")
        lines.append(f"format-check: ## Check formatting")
        lines.append(f"\t{config['formatter']}\n")

    if config.get("linter"):
        lines.append(f".PHONY: lint")
        lines.append(f"lint: ## Run linter")
        lines.append(f"\t{config['linter']}\n")

    if config.get("typecheck"):
        lines.append(f".PHONY: typecheck")
        lines.append(f"typecheck: ## Run type checker")
        lines.append(f"\t{config['typecheck']}\n")

    if config.get("boundaries"):
        lines.append(f".PHONY: boundary-check")
        lines.append(f"boundary-check: ## Enforce module boundaries")
        lines.append(f"\t{config['boundaries']}\n")

    if config.get("test"):
        lines.append(f".PHONY: test")
        lines.append(f"test: ## Run tests")
        lines.append(f"\t{config['test']}\n")

    # Build verify target from available checks
    checks = []
    if config.get("formatter"):
        checks.append("format-check")
    if config.get("linter"):
        checks.append("lint")
    if config.get("typecheck"):
        checks.append("typecheck")
    if config.get("boundaries"):
        checks.append("boundary-check")
    if config.get("test"):
        checks.append("test")

    lines.append(f".PHONY: verify")
    lines.append(f"verify: {' '.join(checks)} ## Run all checks")
    lines.append(f'\t@echo "✓ All checks passed"\n')

    lines.append(".PHONY: help")
    lines.append("help: ## Show this help")
    lines.append('\t@grep -E \'^[a-zA-Z_-]+:.*?## .*$$\' $(MAKEFILE_LIST) \\')
    lines.append('\t\t| awk \'BEGIN {FS = ":.*?## "}; {printf "  \\033[36m%-20s\\033[0m %s\\n", $$1, $$2}\'')

    return "\n".join(lines) + "\n"


def generate_agents_md(stack_name: str, config: dict) -> str:
    """Generate AGENTS.md for the detected stack."""
    sections = [WARNING, ""]
    sections.append("# AGENTS.md\n")
    sections.append(f"Stack: {stack_name}\n")
    sections.append("## Commands\n")
    sections.append("```bash")
    if config.get("bootstrap"):
        sections.append(f"make bootstrap   # set up from fresh clone")
    sections.append(f"make verify      # run all checks (same as CI)")
    sections.append("```\n")
    sections.append("## Non-obvious constraints\n")
    sections.append("<!-- TODO: Add project-specific constraints here. -->")
    sections.append("<!-- Examples: -->")
    sections.append("<!-- - Import boundaries: domain must not import infrastructure -->")
    sections.append("<!-- - Coverage minimum: 80% -->")
    sections.append("<!-- - Protected paths: docs/adr/ requires architecture review -->\n")
    sections.append("## Completion evidence\n")
    sections.append("A task is done when `make verify` passes. Not before.\n")
    return "\n".join(sections)


def generate_adr_template() -> str:
    """Generate an ADR template."""
    return WARNING + """
---
id: ADR-XXX-001
status: proposed
scope:
  - path/to/governed/files/**
---

# Decision title

## Decision

What was decided and how it is enforced.

## Reasons

Why this constraint exists. What breaks without it.

## Verification

```bash
# Command that proves the constraint holds
make verify
```

## Firing condition

How to prove the gate can convict (a drill that plants a violation
and asserts the check catches it). A gate that has never fired is
indistinguishable from a gate that cannot fire.

## Retirement

When to remove this constraint. What conditions would make it
obsolete or harmful.
"""


