def adopt(repo: Path, dry_run: bool = False) -> int:
    """Generate AI-readiness scaffold for the given repo."""
    stacks = detect_stack(repo)

    if not stacks:
        print("No recognized stack detected.", file=sys.stderr)
        print("Looked for:", ", ".join(STACKS.keys()), file=sys.stderr)
        return 1

    primary = stacks[0]
    config = STACKS[primary]

    print(f"Detected stack: {primary}")
    if len(stacks) > 1:
        print(f"Also found: {', '.join(stacks[1:])}")
    print()

    print("⚠ WARNING: Generated files are a STARTING POINT.")
    print("  Review every file before committing.")
    print("  AI agents are not deterministic.")
    print()

    files: dict[str, str] = {}

    # Only generate files that don't already exist
    if not (repo / "Makefile").exists():
        files["Makefile"] = generate_makefile(primary, config)

    if not (repo / "AGENTS.md").exists():
        files["AGENTS.md"] = generate_agents_md(primary, config)

    if not (repo / "SECURITY.md").exists():
        files["SECURITY.md"] = generate_security_md()

    adr_dir = repo / "docs" / "adr"
    if not adr_dir.exists():
        files["docs/adr/ADR-TEMPLATE.md"] = generate_adr_template()

    if not files:
        print("All scaffold files already exist. Nothing to generate.")
        print("Run scripts/ai_readiness_audit.py to check what's missing.")
        return 0

    for path, content in sorted(files.items()):
        full_path = repo / path
        if dry_run:
            print(f"  would create  {path}")
        else:
            full_path.parent.mkdir(parents=True, exist_ok=True)
            full_path.write_text(content)
            print(f"  created  {path}")

    print()
    print(f"Generated {len(files)} file(s) for {primary}.")
    print()
    print("Next steps:")
    print("  1. Review every generated file — they are templates, not truths.")
    print("  2. Run `make verify` and fix any failures.")
    print("  3. Add project-specific constraints to AGENTS.md.")
    print("  4. Create your first ADR from docs/adr/ADR-TEMPLATE.md.")
    print("  5. Delete ADR-TEMPLATE.md after creating a real ADR.")
    print()
    print("Audit your progress:")
    print(f"  python scripts/ai_readiness_audit.py {repo}")

    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Adopt AI-readiness patterns into an existing repository"
    )
    parser.add_argument("repo", type=Path, help="Path to the target repository")
    parser.add_argument("--dry-run", action="store_true", help="Show what would be created")
    parser.add_argument("--detect", action="store_true", help="Detect stack only")
    args = parser.parse_args()

    if not args.repo.is_dir():
        print(f"Not a directory: {args.repo}", file=sys.stderr)
        return 1

    if args.detect:
        stacks = detect_stack(args.repo)
        if stacks:
            print(f"Detected: {', '.join(stacks)}")
        else:
            print("No recognized stack detected.")
        return 0

    return adopt(args.repo, dry_run=args.dry_run)


if __name__ == "__main__":
    sys.exit(main())
