#!/usr/bin/env python3
"""
Adopt AI-readiness patterns into an existing repository.

Detects the project's stack, generates a verification scaffold
(Makefile, AGENTS.md, ADR template, SECURITY.md, CI workflow stub,
drill stubs), and reports what was created.

⚠ WARNING: This tool generates scaffold files from templates.
The output is a STARTING POINT that requires human review.
- Generated linter configs may not match your project's conventions.
- Generated CI workflows need secrets and runner configuration.
- Generated AGENTS.md needs project-specific constraints added.
- Generated drills are stubs — they prove the pattern, not your rules.

Do not merge generated files without reviewing them first.
Run the generated `make verify` and fix any failures before trusting it.

Usage:
    python scripts/adopt.py /path/to/repo              # generate scaffold
    python scripts/adopt.py /path/to/repo --dry-run    # show what would happen
    python scripts/adopt.py /path/to/repo --detect     # detect stack only
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

if sys.version_info < (3, 9):
    sys.exit("adopt.py requires Python 3.9 or newer (found %s)" % sys.version.split()[0])

# ponytail: detection by file presence, fine for common stacks;
# replace with a plugin registry if this grows beyond 10 stacks

